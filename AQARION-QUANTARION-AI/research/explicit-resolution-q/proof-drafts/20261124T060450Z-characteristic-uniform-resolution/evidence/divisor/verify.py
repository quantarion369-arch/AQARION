def compute(expected_shifts):
    need(
        TOP == (4,4,4,4,4),
        "Unexpected top multidegree",
    )

    facets = [
        list(map(int, sp.eye(5).row(i)))
        for i in range(4)
    ]
    facets += [
        [int(h in pair) for h in range(4)] + [-1]
        for pair in PAIRS
    ]

    facet_matrix = sp.Matrix(facets)

    need(facet_matrix.rank() == 5, "Facet embedding rank")
    need(
        facet_matrix*sp.Matrix(KAPPA) == sp.ones(10,1),
        "Canonical translate",
    )
    need(
        all(inside(g) and scalar(g) > 0 for g in G),
        "Positive semigroup generators",
    )

    degrees = []

    for a in itertools.product(range(5), repeat=4):
        sums = [a[i]+a[j] for i,j in PAIRS]

        degrees.extend(
            a+(k,)
            for k in range(
                max(sums)-4,
                min(sums)+1,
            )
        )

    need(
        len(degrees) == 835
        and len(set(degrees)) == 835,
        "Complete degree interval count",
    )
    need(
        all(
            inside(b)
            and inside(tuple(x-y for x,y in zip(TOP,b)))
            for b in degrees
        ),
        "Degree interval membership",
    )

    orbit_count = len({
        (tuple(sorted(b[:4])), b[4])
        for b in degrees
    })
    need(orbit_count == 138, "Orbit count crosscheck")

    subset_totals = [(0,)*5]*1024

    for mask in range(1,1024):
        bit = mask & -mask
        j = bit.bit_length()-1

        subset_totals[mask] = tuple(
            x+y
            for x,y in zip(
                subset_totals[mask ^ bit],
                G[j],
            )
        )

    betti = collections.Counter()
    boundary_count = 0
    chain_checks = 0
    maximum_faces = 0
    degree_rows = []
    torsion_cases = []

    certificate_path = OUT/"DIVISOR_CERTIFICATES.jsonl"

    with certificate_path.open("w", buffering=1) as stream:
        for number, b in enumerate(degrees, 1):
            faces = collections.defaultdict(list)

            for mask, total in enumerate(subset_totals):
                residual = tuple(
                    x-y for x,y in zip(b,total)
                )
                if inside(residual):
                    faces[mask.bit_count()-1].append(mask)

            all_faces = {
                mask
                for masks in faces.values()
                for mask in masks
            }

            need(0 in all_faces, "Empty face absent")

            for mask in all_faces:
                for vertex in range(10):
                    if mask >> vertex & 1:
                        need(
                            (mask ^ (1 << vertex)) in all_faces,
                            "Face set is not a simplicial complex",
                        )

            top_dimension = max(faces)
            ranks = {}
            torsions = {}
            boundary_records = []
            previous_columns = None

            for d in range(top_dimension+1):
                target = {
                    mask: i
                    for i, mask in enumerate(faces[d-1])
                }

                D = sp.zeros(
                    len(target),
                    len(faces[d]),
                )

                rows = {}
                columns = []

                for column, mask in enumerate(faces[d]):
                    entries = {}
                    position = 0

                    for vertex in range(10):
                        if mask >> vertex & 1:
                            row = target[
                                mask ^ (1 << vertex)
                            ]
                            value = (-1)**position
                            position += 1

                            D[row,column] = value
                            rows.setdefault(row, {})[column] = value
                            entries[row] = value

                    columns.append(entries)

                if previous_columns is not None:
                    for column in columns:
                        product = {}

                        for middle, a in column.items():
                            for row, x in previous_columns[middle].items():
                                product[row] = (
                                    product.get(row, 0)+a*x
                                )

                        need(
                            all(x == 0 for x in product.values()),
                            "Boundary squared is nonzero",
                        )

                    chain_checks += 1

                previous_columns = columns

                smith = smith_normal_form(D, domain=sp.ZZ)

                diagonal = [
                    abs(int(smith[i,i]))
                    for i in range(min(smith.shape))
                    if smith[i,i]
                ]

                need(
                    all(
                        diagonal[i+1] % diagonal[i] == 0
                        for i in range(len(diagonal)-1)
                    ),
                    "Invalid Smith divisibility chain",
                )

                trace = unit_reduce(rows)
                replay_unit_trace(rows, trace)

                need(
                    len(trace) == len(diagonal),
                    "Unit rank differs from Smith rank",
                )
                need(
                    all(x == 1 for x in diagonal),
                    "Nonunit Smith factor found",
                )

                ranks[d] = len(diagonal)
                torsions[d] = [
                    x for x in diagonal if x > 1
                ]
                boundary_count += 1

                boundary_records.append({
                    "dimension": d,
                    "rows": D.rows,
                    "columns": D.cols,
                    "rank": len(diagonal),
                    "nonzero_smith_diagonal": diagonal,
                    "integer_unit_pivot_trace": trace,
                })

            homology = []
            has_betti = False

            for d in range(-1, top_dimension+1):
                free_rank = (
                    len(faces[d])
                    - ranks.get(d, 0)
                    - ranks.get(d+1, 0)
                )
                torsion = torsions.get(d+1, [])

                need(
                    free_rank >= 0,
                    "Negative homology rank",
                )

                if torsion:
                    torsion_cases.append({
                        "b": b,
                        "dimension": d,
                        "torsion": torsion,
                    })

                if free_rank:
                    betti[d+1,b] += free_rank
                    has_betti = True

                homology.append({
                    "dimension": d,
                    "free_rank": free_rank,
                    "torsion_invariant_factors": torsion,
                })

            maximum_faces = max(
                maximum_faces, len(all_faces)
            )

            degree_rows.append([
                *b,
                scalar(b),
                len(all_faces),
                has_betti,
            ])

            stream.write(json.dumps({
                "degree": b,
                "face_masks": sorted(all_faces),
                "boundaries": boundary_records,
                "reduced_integral_homology": homology,
            }, separators=(",",":")) + "\n")

            if number % 50 == 0 or number == len(degrees):
                log(
                    "  Degrees complete: %d / %d"
                    % (number, len(degrees))
                )

    # The archived shifts enter only now, after the full computation.
    expected = collections.Counter(
        (i, tuple(b))
        for i, shifts in enumerate(expected_shifts)
        for b in shifts
    )

    need(
        betti == expected,
        "Computed multigraded Betti data differs from archived shifts",
    )

    for (i,b), multiplicity in betti.items():
        dual_degree = tuple(
            x-y for x,y in zip(TOP,b)
        )
        need(
            betti[5-i,dual_degree] == multiplicity,
            "Betti self-duality check",
        )

    aggregated = collections.Counter()
    weighted = collections.Counter()

    for (i,b), multiplicity in betti.items():
        aggregated[i] += multiplicity
        weighted[i,scalar(b)] += multiplicity

    need(
        [aggregated[i] for i in range(6)]
        == [1,14,35,35,14,1],
        "Betti totals",
    )
    need(not torsion_cases, "Integral homology torsion found")
    need(
        boundary_count == 2956 and len(betti) == 54,
        "Coverage crosscheck",
    )

    write_csv(
        "DEGREE_INTERVAL.csv",
        [
            "a0","a1","a2","a3","k",
            "scalar_degree",
            "faces_including_empty",
            "nonzero_betti",
        ],
        degree_rows,
    )

    write_csv(
        "BETTI_MULTIGRADED.csv",
        [
            "homological_degree",
            "a0","a1","a2","a3","k",
            "scalar_degree",
            "multiplicity",
        ],
        (
            [i,*b,scalar(b),multiplicity]
            for (i,b),multiplicity in sorted(betti.items())
        ),
    )

    write_csv(
        "BETTI_WEIGHTED.csv",
        [
            "homological_degree",
            "scalar_degree",
            "multiplicity",
        ],
        (
            [i,d,multiplicity]
            for (i,d),multiplicity in sorted(weighted.items())
        ),
    )

    save(
        "BETTI_TOTALS.json",
        {str(i): aggregated[i] for i in range(6)},
    )
    save("TORSION_CASES.json", torsion_cases)

    save("MODEL.json", {
        "generator_names": NAMES,
        "generators": G,
        "facets": facets,
        "kappa": KAPPA,
        "top_multidegree": TOP,
        "scalar_degree": "a0+a1+a2+a3-k",
        "degree_count": len(degrees),
        "symmetry_orbits_counted_but_not_used": orbit_count,
        "face_encoding": (
            "10-bit mask; bit j corresponds to generator j"
        ),
        "boundary_orientation": (
            "delete vertices in increasing order; "
            "coefficient (-1)^position"
        ),
        "homology": (
            "augmented/reduced; empty face has dimension -1"
        ),
    })

    return {
        "degrees": len(degrees),
        "orbit_count": orbit_count,
        "symmetry_used_to_reduce_computation": False,
        "boundary_smith_forms": boundary_count,
        "integer_unit_reductions": boundary_count,
        "unit_traces_replayed": boundary_count,
        "boundary_composition_checks": chain_checks,
        "torsion_cases": len(torsion_cases),
        "nonzero_multigraded_positions": len(betti),
        "betti_totals": [
            aggregated[i] for i in range(6)
        ],
        "maximum_faces_including_empty": maximum_faces,
        "archived_multigraded_shifts_match": True,
    }

