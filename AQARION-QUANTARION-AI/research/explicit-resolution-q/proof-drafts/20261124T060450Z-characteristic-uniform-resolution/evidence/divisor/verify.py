def unit_reduce(rows):
    rows = {
        i: dict(row)
        for i, row in rows.items()
        if row
    }
    trace = []

    while rows:
        found = next(
            (
                (i,j,value)
                for i, row in rows.items()
                for j, value in row.items()
                if abs(value) == 1
            ),
            None,
        )

        need(
            found is not None,
            "Unit-pivot strategy stalled; this is NOT "
            "by itself a torsion counterexample",
        )

        i, j, value = found
        pivot = rows.pop(i)
        trace.append([i,j,value])

        for r, row in list(rows.items()):
            if j not in row:
                continue

            factor = row[j]*value

            for column, x in pivot.items():
                new = row.get(column, 0)-factor*x

                if new:
                    row[column] = new
                else:
                    row.pop(column, None)

            if not row:
                rows.pop(r)

    return trace

def replay_unit_trace(rows, trace):
    rows = {
        i: dict(row)
        for i, row in rows.items()
        if row
    }

    for i, j, value in trace:
        need(
            i in rows
            and rows[i].get(j) == value
            and abs(value) == 1,
            "Invalid integral pivot witness",
        )

        pivot = rows.pop(i)

        for r, row in list(rows.items()):
            factor = row.get(j, 0)*value

            if not factor:
                continue

            for column, x in pivot.items():
                new = row.get(column, 0)-factor*x

                if new:
                    row[column] = new
                else:
                    row.pop(column, None)

            if not row:
                rows.pop(r)

    need(
        not rows,
        "Integral pivot witness leaves a nonzero residual",
    )

